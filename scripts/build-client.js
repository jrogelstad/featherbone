/*jslint node unordered*/
/*
    Build the production client: bundle and minify the module scripts
    index_debug.html loads into client/clientmin.js, and write index.html
    to match.

    index_debug.html is the one list of what the client is. Every
    <script type="module"> it names (the models, components, pages, and
    through their imports everything else) goes into the bundle in the
    order it names them, so a file added to the debug page reaches
    production without a second list to keep. index.html is then the
    debug page with those scripts replaced by the bundle and each
    vendor script swapped for its .min.js sibling where one exists.
    Edit index_debug.html, never index.html or clientmin.js.

    The linter shim (client/javascript-lint.js, which imports the 500 KB
    jslint) stays a separate script: only the script editor needs it.

    Usage:

        npm run build:client                  write both files
        npm run build:client -- --check       change nothing; exit 1
                                              if either is out of date
        npm run build:client -- --sourcemap   also write
                                              client/clientmin.js.map
*/
"use strict";

const fs = require("fs");
const path = require("path");
const zlib = require("zlib");

const ROOT = path.resolve(__dirname, "..");
const DEBUG_HTML = path.join(ROOT, "index_debug.html");
const PROD_HTML = path.join(ROOT, "index.html");
const BUNDLE = path.join(ROOT, "client", "clientmin.js");
const BUNDLE_SRC = "/client/clientmin.js";

// Module scripts the bundle leaves out
const SEPARATE = new Set(["/client/javascript-lint.js"]);

const BANNER = (
    "/* Featherbone client bundle. Generated by `npm run build:client` " +
    "from index_debug.html; do not edit. See license.txt. */"
);
const NOTICE = (
    "<!-- Generated from index_debug.html by `npm run build:client`. " +
    "Edit that file, not this one. -->"
);

const SCRIPT_TAG = /<script\b([^>]*)>\s*<\/script>/g;

function escape(str) {
    return str.replace(/[.*+?\^${}()|\[\]\\]/g, "\\$&");
}

function attr(tag, name) {
    let found = new RegExp("\\b" + name + "=\"([^\"]*)\"").exec(tag);
    return (
        found
        ? found[1]
        : undefined
    );
}

/**
    The scripts a page loads, in order.

    @param {String} html
    @return {Array} {tag, src, isModule}
*/
function scripts(html) {
    return Array.from(html.matchAll(SCRIPT_TAG)).map(function (found) {
        return {
            tag: found[0],
            src: attr(found[1], "src"),
            isModule: attr(found[1], "type") === "module"
        };
    });
}

/**
    The module scripts that go into the bundle, in load order.

    @param {String} html
    @return {Array} Paths such as "/client/main.js"
*/
function bundled(html) {
    return scripts(html).filter(
        (s) => s.isModule && s.src && !SEPARATE.has(s.src)
    ).map((s) => s.src);
}

/**
    The production page for a debug page.

    @param {String} html Contents of index_debug.html
    @param {Function} [exists] Whether a root-relative path is on disk
    @return {String}
*/
function productionHtml(html, exists) {
    let inBundle = new Set(bundled(html));
    let placed = false;
    let ret = html;

    exists = exists || function (src) {
        return fs.existsSync(path.join(ROOT, src));
    };

    scripts(html).forEach(function (s) {
        let min = (
            (s.src && !s.isModule)
            ? s.src.replace(/\.js$/, ".min.js")
            : undefined
        );
        let line = new RegExp("^[ \\t]*" + escape(s.tag) + "[ \\t]*\\n", "m");

        if (inBundle.has(s.src)) {
            ret = ret.replace(line, function () {
                if (placed) {
                    return "";
                }
                placed = true;
                return (
                    "        <script src=\"" + BUNDLE_SRC +
                    "\" type=\"module\"></script>\n"
                );
            });
        } else if (
            min && min !== s.src && s.src.startsWith("/node_modules/") &&
            exists(min)
        ) {
            ret = ret.replace(s.tag, s.tag.replace(s.src, min));
        }
    });

    return ret.replace(
        "<!doctype html>\n",
        "<!doctype html>\n" + NOTICE + "\n"
    );
}

/**
    Bundle and minify. Nothing is written.

    @param {String} html Contents of index_debug.html
    @param {Object} [options] sourcemap
    @return {Promise} {code, map, inputs, external, files}
*/
async function bundle(html, options) {
    let esbuild;
    let wantMap = Boolean(options && options.sourcemap);
    let files = bundled(html);
    let result;

    try {
        esbuild = require("esbuild");
    } catch (ignore) {
        esbuild = undefined;
    }
    if (!esbuild) {
        throw new Error("esbuild is not installed. Run `npm install`.");
    }

    files.forEach(function (src) {
        if (!fs.existsSync(path.join(ROOT, src))) {
            throw new Error(
                "index_debug.html loads " + src + ", which does not exist."
            );
        }
    });

    result = await esbuild.build({
        stdin: {
            contents: files.map((src) => "import \"." + src + "\";").join("\n"),
            resolveDir: ROOT,
            sourcefile: "clientmin-entry.js"
        },
        outfile: BUNDLE,
        bundle: true,
        format: "esm",
        target: "es2020",
        minify: true,
        legalComments: "none",
        banner: {js: BANNER},
        sourcemap: (
            wantMap
            ? "linked"
            : false
        ),
        metafile: true,
        logLevel: "silent",
        write: false
    });

    return {
        code: result.outputFiles.find((o) => o.path === BUNDLE).text,
        map: (
            wantMap
            ? result.outputFiles.find((o) => o.path === BUNDLE + ".map").text
            : undefined
        ),
        inputs: Object.keys(result.metafile.inputs),
        external: Object.values(result.metafile.outputs).flatMap(
            function (out) {
                return out.imports.filter(
                    (i) => i.external
                ).map(
                    (i) => i.path
                );
            }
        ),
        files
    };
}

function kb(n) {
    let size = n / 1024;

    return size.toFixed(1) + " KB";
}

function read(file) {
    return (
        fs.existsSync(file)
        ? fs.readFileSync(file, "utf8")
        : ""
    );
}

async function main(argv) {
    let check = argv.includes("--check");
    let html = read(DEBUG_HTML);
    let built = await bundle(html, {sourcemap: argv.includes("--sourcemap")});
    let page = productionHtml(html);
    let before = read(BUNDLE).length;
    let stale = [];

    if (read(BUNDLE) !== built.code) {
        stale.push("client/clientmin.js");
    }
    if (read(PROD_HTML) !== page) {
        stale.push("index.html");
    }

    if (check) {
        if (stale.length) {
            console.error(
                "Out of date: " + stale.join(", ") +
                ". Run `npm run build:client`."
            );
            return 1;
        }
        console.log("clientmin.js and index.html are up to date.");
        return 0;
    }

    fs.writeFileSync(BUNDLE, built.code);
    fs.writeFileSync(PROD_HTML, page);
    if (built.map) {
        fs.writeFileSync(BUNDLE + ".map", built.map);
    }

    console.log(
        "clientmin.js: " + built.files.length + " scripts, " +
        built.inputs.length + " files, " + kb(built.code.length) +
        " (" + kb(zlib.gzipSync(built.code).length) + " gzipped; was " +
        kb(before) + ")"
    );
    console.log(
        "index.html: " + (
            stale.includes("index.html")
            ? "rewritten"
            : "unchanged"
        )
    );
    return 0;
}

/**
    Build the bundle if what is on disk is not what the sources say, and
    say what happened. The server calls this as it starts (server.js), so
    `npm start` is all a deployment needs: client/clientmin.js is built
    rather than committed.

    It used to be committed, and every merge that touched client code
    conflicted on 400 KB of minified output -- four times in two days,
    each one resolved by rebuilding it anyway (John, Oct 2026).

    A build that fails is only fatal when there is no bundle to fall back
    on: a server that cannot write to its own checkout should still come
    up and serve the bundle that is already there.

    @method ensure
    @param {Object} [options] quiet, file (where to write; the bundle)
    @return {Promise} {built, reason}
*/
async function ensure(options) {
    let quiet = Boolean(options && options.quiet);
    let where = (options && options.file) || BUNDLE;
    let held = read(where);
    let built = await bundle(read(DEBUG_HTML)).then(
        (out) => out,
        (err) => ({failed: err})
    );
    let fatal;
    let wrote;

    function say(message) {
        if (!quiet) {
            console.log(message);
        }
    }

    /*
        A server that cannot write to its own checkout still comes up on
        the bundle that is already there; only an absent one is fatal.
    */
    function fallBack(what, err) {
        if (!held) {
            return new Error(
                "The client bundle is missing and " + what + ": " +
                err.message
            );
        }
        console.warn(
            "Client bundle " + what + " (" + err.message +
            "); serving the one on disk."
        );
        return undefined;
    }

    if (built.failed) {
        fatal = fallBack("cannot be built", built.failed);

        if (fatal) {
            throw fatal;
        }
        return {built: false, reason: built.failed.message};
    }

    if (held === built.code) {
        say("Client bundle is current.");
        return {built: false, reason: "current"};
    }

    wrote = (function () {
        try {
            fs.writeFileSync(where, built.code);
        } catch (err) {
            return err;
        }
    }());

    if (wrote) {
        fatal = fallBack("could not be written", wrote);

        if (fatal) {
            throw fatal;
        }
        return {built: false, reason: wrote.message};
    }

    say(
        "Client bundle built: " + built.files.length + " scripts, " +
        built.inputs.length + " files, " + kb(built.code.length) + "."
    );

    return {built: true, reason: "written"};
}

module.exports = {bundle, bundled, ensure, productionHtml, scripts};

if (require.main === module) {
    main(process.argv.slice(2)).then(function (code) {
        process.exitCode = code;
    }).catch(function (err) {
        console.error(err.message);
        process.exitCode = 1;
    });
}
