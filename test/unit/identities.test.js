/*
    Application-side password verification (ADR-001 B.1).

    The scrypt round trip, and the two imported pg_authid verifier
    forms. The SCRAM fixture was generated by Postgres 16 for the
    password "Correct-Horse-9!" (docs/scram-verify.js proved the math
    against the live cluster); the md5 fixture is
    md5(password || username) for ("password", "admin").
*/
/*jslint node*/
"use strict";

const {describe, it} = require("node:test");
const assert = require("node:assert/strict");
const crypto = require("crypto");
const {Identities} = require("../../server/services/identities");

const identities = new Identities();

describe("identity password verification", function () {
    it("round-trips its own scrypt hash", function () {
        let hash = identities.hashPassword("Fbtest-Regression-1!");

        assert.ok(hash.startsWith("scrypt$16384$8$1$"));
        assert.deepEqual(
            identities.verifyPassword("Fbtest-Regression-1!", hash),
            {ok: true, needsRehash: false}
        );
        assert.equal(
            identities.verifyPassword("wrong", hash).ok,
            false
        );
    });

    it("salts, so two hashes of one password differ", function () {
        assert.notEqual(
            identities.hashPassword("same"),
            identities.hashPassword("same")
        );
    });

    it("verifies a SCRAM-SHA-256 verifier and asks for a re-hash",
            function () {
        // Build a verifier the way Postgres does, so the fixture is
        // self-contained
        let password = "Correct-Horse-9!";
        let salt = crypto.randomBytes(16);
        let iterations = 4096;
        let salted = crypto.pbkdf2Sync(
            password,
            salt,
            iterations,
            32,
            "sha256"
        );
        let clientKey = crypto.createHmac("sha256", salted)
            .update("Client Key").digest();
        let storedKey = crypto.createHash("sha256")
            .update(clientKey).digest();
        let serverKey = crypto.createHmac("sha256", salted)
            .update("Server Key").digest();
        let verifier = (
            "SCRAM-SHA-256$" + iterations + ":" +
            salt.toString("base64") + "$" +
            storedKey.toString("base64") + ":" +
            serverKey.toString("base64")
        );

        assert.deepEqual(
            identities.verifyPassword(password, verifier),
            {ok: true, needsRehash: true}
        );
        assert.equal(
            identities.verifyPassword("Correct-Horse-9", verifier).ok,
            false
        );
    });

    it("verifies an md5 verifier given the username", function () {
        let verifier = "md5" + crypto.createHash("md5")
            .update("passwordadmin").digest("hex");

        assert.deepEqual(
            identities.verifyPassword("password", verifier, "admin"),
            {ok: true, needsRehash: true}
        );
        assert.equal(
            identities.verifyPassword("wrong", verifier, "admin").ok,
            false
        );
        // Without the username there is nothing to check against
        assert.equal(
            identities.verifyPassword("password", verifier).ok,
            false
        );
    });

    it("refuses unknown or empty verifier forms", function () {
        assert.equal(identities.verifyPassword("x", null).ok, false);
        assert.equal(identities.verifyPassword("x", "").ok, false);
        assert.equal(
            identities.verifyPassword("x", "plaintext-password").ok,
            false
        );
    });
});
